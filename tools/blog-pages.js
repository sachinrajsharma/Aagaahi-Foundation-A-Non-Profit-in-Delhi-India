// tools/blog-pages.js — builds the static Blog: docs/blog/index.html, docs/blog/<slug>/index.html, sitemap.xml, robots.txt,
// the "From our blog" block on the home page, and includes/posts.json (read by the PHP version).
// Every post page carries the SEO markup the dashboard's standard asks for: unique title and description, canonical URL,
// Open Graph and Twitter cards, and structured data (BlogPosting, BreadcrumbList and FAQPage).
const fs = require('fs');
const path = require('path');
const { loadPosts, esc } = require('./posts-lib');

const fmtDate = (iso) => { try { return new Date(iso).toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Asia/Kolkata' }); } catch (e) { return ''; } };
const readMin = (p) => Math.max(1, Math.round(p.words / 200));
const cut = (s, n) => { s = String(s || '').trim(); return s.length <= n ? s : s.slice(0, n - 1).replace(/\s+\S*$/, '') + '…'; };
const ld = (obj) => '<script type="application/ld+json">' + JSON.stringify(obj).replace(/</g, '\\u003c') + '</script>';

function load(root, siteUrl) { return loadPosts(root, siteUrl); }

function cardsHtml(posts, hrefPre, imgPre) {
  return posts.map((p) => `<a class="post-card" href="${hrefPre}${esc(p.slug)}/">` +
    (p.cover_rel ? `<img src="${imgPre}${esc(p.cover_rel)}" alt="${esc(p.cover_alt)}" loading="lazy">` : '') +
    `<div class="pc-body"><span class="post-cat">${esc(p.category)}</span><h3>${esc(p.title)}</h3><p>${esc(p.excerpt)}</p><small>${esc(fmtDate(p.date))} · ${readMin(p)} min read</small></div></a>`).join('');
}

// "From our blog" block for the home page (links are relative to the site root).
function latestSection(posts) {
  if (!posts.length) return '';
  return `<section id="blog"><div class="wrap"><h2 class="reveal">From our blog</h2><p>Practical guides from our programmes: money and online safety, hygiene, road safety and workplace rights.</p>` +
    `<div class="post-grid">${cardsHtml(posts.slice(0, 4), 'blog/', '')}</div><p style="margin-top:1.5rem"><a class="btn o" href="blog/">All posts</a></p></div></section>\n`;
}

function build({ root, docs, ngo, siteUrl, cmsUrl, cmsSite, posts }) {
  // ---- generated file for the PHP version
  fs.writeFileSync(path.join(root, 'includes', 'posts.json'), JSON.stringify({
    _note: 'Generated by tools/build-static.js from includes/posts/*.html. Edit those files (or use the dashboard), not this one.',
    site_url: siteUrl,   // the address baked into links/images below; database/seed.php turns it into root-relative paths
    posts: posts.map((p) => ({ slug: p.slug, title: p.title, date: p.date, category: p.category, excerpt: p.excerpt, meta_title: p.meta_title, meta_desc: p.meta_desc,
      cover: p.cover, cover_rel: p.cover_rel, cover_alt: p.cover_alt, author: p.author, keyphrase: p.keyphrase, faqs: p.faqs, content: p.content })),
  }, null, 1) + '\n');

  const canonicalFor = (rel) => (siteUrl ? `<link rel="canonical" href="${esc(siteUrl + '/' + rel)}">` : '');

  function shell({ title, pre, body, desc, rel, ogImage, ogType, schema, extraScripts }) {
    const full = `${title} — ${ngo.name}`;
    return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title.length > 62 ? title : full)}</title>
<meta name="description" content="${esc(desc || ngo.mission)}">
${canonicalFor(rel)}
<meta property="og:site_name" content="${esc(ngo.name)}">
<meta property="og:type" content="${ogType || 'website'}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc || ngo.mission)}">
${siteUrl ? `<meta property="og:url" content="${esc(siteUrl + '/' + rel)}">` : ''}
${ogImage ? `<meta property="og:image" content="${esc(ogImage)}">` : ''}
<meta name="twitter:card" content="${ogImage ? 'summary_large_image' : 'summary'}">
<meta name="twitter:title" content="${esc(title)}">
<meta name="twitter:description" content="${esc(desc || ngo.mission)}">
${ogImage ? `<meta name="twitter:image" content="${esc(ogImage)}">` : ''}
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Nunito:wght@400;600;800&family=Fraunces:wght@600;800&display=swap" rel="stylesheet">
<link rel="stylesheet" href="${pre}assets/common.css">
<link rel="stylesheet" href="${pre}assets/site.css">
${(schema || []).join('\n')}
</head>
<body>
<nav><div class="wrap"><a class="brand" href="${pre}"><span class="logo-emoji">${esc(ngo.logo)}</span> ${esc(ngo.name)}</a>
  <div><a class="m" href="${pre}#work">Our Work</a><a class="m" href="${pre}study/">Study</a><a class="m" href="${pre}blog/">Blog</a><a class="m" href="${pre}#contact">Contact</a> <span class="navauth"><a class="m auth" data-auth="in" href="${pre}study/#/login">Log in</a><a class="btn" data-auth="in" style="margin-left:1rem;padding:.6rem 1.3rem" href="${pre}study/#/join">Create account</a><a class="btn" data-auth="out" hidden style="margin-left:1rem;padding:.6rem 1.3rem" href="${pre}study/#/me">My progress</a></span></div></div></nav>
<div class="wrap powered-row"><div class="powered">Powered by <a href="https://vidaara.org" target="_blank" rel="noopener">vidaara.org</a></div></div>
<section><div class="wrap" style="max-width:${rel === 'blog/' ? '1040' : '820'}px">${body}</div></section>
<footer>© ${new Date().getFullYear()} ${esc(ngo.name)} · ${esc(ngo.reg_note)}</footer>
<script src="${pre}assets/nav.js"></script>
${extraScripts || ''}
</body>
</html>
`;
  }

  // ---- blog index
  const listBody = posts.length
    ? `<h1 style="color:var(--g1)">Blog</h1><p class="st-sub">Practical guides from our programmes in Delhi.</p><div class="post-grid">${cardsHtml(posts, '', '../')}</div>`
    : `<h1 style="color:var(--g1)">Blog</h1><p class="st-sub">Stories and updates from ${esc(ngo.name)} will appear here soon.</p>`;
  fs.mkdirSync(path.join(docs, 'blog'), { recursive: true });
  fs.writeFileSync(path.join(docs, 'blog', 'index.html'), shell({
    title: 'Blog', pre: '../', rel: 'blog/', desc: `Practical guides on online safety, hygiene, road safety and workplace rights from ${ngo.name}, a non-profit in Delhi.`,
    ogImage: posts[0] ? posts[0].cover : '', body: `<div id="cms-blog" data-cms="${esc(cmsUrl)}" data-site="${esc(cmsSite)}">${listBody}</div>`,
    extraScripts: '<script src="../assets/blog.js"></script>',
  }));

  // ---- one page per post
  posts.forEach((p) => {
    const url = siteUrl + '/blog/' + p.slug + '/';
    const others = posts.filter((x) => x.slug !== p.slug).slice(0, 3);
    const org = { '@type': 'Organization', name: ngo.name, url: siteUrl + '/' };
    const schema = [
      ld({ '@context': 'https://schema.org', '@type': 'BlogPosting', headline: cut(p.title, 110), description: p.meta_desc,
        image: p.cover ? [p.cover] : undefined, mainEntityOfPage: { '@type': 'WebPage', '@id': url }, datePublished: new Date(p.date).toISOString(),
        dateModified: new Date(p.date).toISOString(), author: org, publisher: org, wordCount: p.words, articleSection: p.category || undefined, keywords: p.keyphrase || undefined, inLanguage: 'en-IN' }),
      ld({ '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: siteUrl + '/' }, { '@type': 'ListItem', position: 2, name: 'Blog', item: siteUrl + '/blog/' },
        { '@type': 'ListItem', position: 3, name: p.title, item: url }] }),
    ];
    if (p.faqs.length) schema.push(ld({ '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: p.faqs.map((f) => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })) }));
    const body = `<nav class="crumbs"><a href="../../">Home</a> <i>›</i> <a href="../">Blog</a> <i>›</i> <span>${esc(cut(p.title, 48))}</span></nav>` +
      `<article class="article"><p class="post-cat">${esc(p.category)}</p><h1>${esc(p.title)}</h1>` +
      `<p class="post-meta">By ${esc(p.author)} · ${esc(fmtDate(p.date))} · ${readMin(p)} min read</p>` +
      (p.cover_rel ? `<figure class="post-cover"><img src="../../${esc(p.cover_rel)}" alt="${esc(p.cover_alt)}"></figure>` : '') +
      `${p.content}</article>` +
      `<div class="study-band" style="margin:2.5rem 0 0"><h2>Want to learn more?</h2><p>Students in Class 1 to 12 can study for free on our Study page, and we run sessions for schools and workplaces.</p><a class="btn" href="../../study/">Start studying</a></div>` +
      (others.length ? `<h2 style="margin-top:2.5rem">More from our blog</h2><div class="post-grid">${cardsHtml(others, '../', '../../')}</div>` : '');
    fs.mkdirSync(path.join(docs, 'blog', p.slug), { recursive: true });
    fs.writeFileSync(path.join(docs, 'blog', p.slug, 'index.html'), shell({
      title: p.meta_title, pre: '../../', rel: 'blog/' + p.slug + '/', desc: p.meta_desc, ogImage: p.cover, ogType: 'article', schema, body }));
  });

  // ---- sitemap + robots (need the public address)
  if (siteUrl) {
    const day = (d) => new Date(d).toISOString().slice(0, 10);
    const urls = [[siteUrl + '/', null], [siteUrl + '/study/', null], [siteUrl + '/blog/', posts[0] ? day(posts[0].date) : null]].concat(posts.map((p) => [siteUrl + '/blog/' + p.slug + '/', day(p.date)]));
    fs.writeFileSync(path.join(docs, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
      urls.map(([u, m]) => `  <url><loc>${esc(u)}</loc>${m ? `<lastmod>${m}</lastmod>` : ''}</url>`).join('\n') + '\n</urlset>\n');
    fs.writeFileSync(path.join(docs, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`);
  }
}

module.exports = { load, latestSection, build, fmtDate, readMin };
